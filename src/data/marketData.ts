// Helper to generate realistic historical price points
function generateHistory(basePrice: number, volatility: number, trend: number): Record<Timeframe, PricePoint[]> {
  const timeframes: Timeframe[] = ['1D', '5D', '1M', '3M', '6M', '1Y', '5Y', 'ALL'];
  const result: Partial<Record<Timeframe, PricePoint[]>> = {};

  timeframes.forEach((tf) => {
    let count = 24;
    let timeLabels: string[] = [];

    if (tf === '1D') {
      count = 26; // Every 15 min from 9:30 to 16:00
      timeLabels = ['09:30', '09:45', '10:00', '10:15', '10:30', '10:45', '11:00', '11:15', '11:30', '11:45', '12:00', '12:15', '12:30', '12:45', '13:00', '13:15', '13:30', '13:45', '14:00', '14:15', '14:30', '14:45', '15:00', '15:15', '15:30', '16:00'];
    } else if (tf === '5D') {
      count = 20;
      timeLabels = ['Mon 10:00', 'Mon 14:00', 'Tue 10:00', 'Tue 14:00', 'Wed 10:00', 'Wed 14:00', 'Thu 10:00', 'Thu 14:00', 'Fri 10:00', 'Fri 14:00', 'Mon 10:00', 'Mon 14:00', 'Tue 10:00', 'Tue 14:00', 'Wed 10:00', 'Wed 14:00', 'Thu 10:00', 'Thu 14:00', 'Fri 10:00', 'Fri 16:00'];
    } else if (tf === '1M') {
      count = 30;
      timeLabels = Array.from({ length: 30 }, (_, i) => `Day ${i + 1}`);
    } else if (tf === '3M') {
      count = 30;
      timeLabels = Array.from({ length: 30 }, (_, i) => `Week ${Math.floor(i / 2) + 1}`);
    } else if (tf === '6M') {
      count = 26;
      timeLabels = ['Jan', 'Jan 15', 'Feb', 'Feb 15', 'Mar', 'Mar 15', 'Apr', 'Apr 15', 'May', 'May 15', 'Jun', 'Jun 15', 'Jul', 'Jul 15', 'Aug', 'Aug 15', 'Sep', 'Sep 15', 'Oct', 'Oct 15', 'Nov', 'Nov 15', 'Dec', 'Dec 15', 'Jan', 'Now'];
    } else if (tf === '1Y') {
      count = 24;
      timeLabels = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec', 'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Now'];
    } else if (tf === '5Y') {
      count = 20;
      timeLabels = ['2020', '2020 Q3', '2021', '2021 Q3', '2022', '2022 Q3', '2023', '2023 Q3', '2024', '2024 Q3', '2025', '2025 Q3', '2026', 'Now'];
    } else {
      count = 20;
      timeLabels = ['2015', '2016', '2017', '2018', '2019', '2020', '2021', '2022', '2023', '2024', '2025', '2026'];
    }

    let current = basePrice * (1 - (trend * count * 0.005));
    const points: PricePoint[] = [];

    for (let i = 0; i < timeLabels.length; i++) {
      const delta = (Math.sin(i * 0.7) + (Math.random() - 0.48)) * (basePrice * volatility * 0.01) + (basePrice * trend * 0.003);
      current = Math.max(current + delta, basePrice * 0.2);
      const open = current - (Math.random() - 0.5) * (basePrice * 0.008);
      const high = Math.max(open, current) + Math.random() * (basePrice * 0.006);
      const low = Math.min(open, current) - Math.random() * (basePrice * 0.006);
      const volume = Math.floor(Math.random() * 500000 + 100000);

      points.push({
        time: timeLabels[i] || `T${i}`,
        price: Number(current.toFixed(2)),
        open: Number(open.toFixed(2)),
        high: Number(high.toFixed(2)),
        low: Number(low.toFixed(2)),
        close: Number(current.toFixed(2)),
        volume,
      });
    }

    // Ensure last point aligns with current basePrice
    if (points.length > 0) {
      points[points.length - 1].price = basePrice;
      points[points.length - 1].close = basePrice;
    }

    result[tf] = points;
  });

  return result as Record<Timeframe, PricePoint[]>;
}

